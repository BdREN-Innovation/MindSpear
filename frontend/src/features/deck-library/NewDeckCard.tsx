"use client";

import { useRef, useState } from "react";
import Image from "next/image";
import { useRouter } from "next/navigation";
import { toast } from "react-toastify";
import { FaPlus } from "react-icons/fa6";
import { ImFilesEmpty } from "react-icons/im";
import { Loader2 } from "lucide-react";
import { cn } from "@/lib/utils";
import { Modal } from "@/components/ui";
import { DocumentToQuestionsModal, type GeneratedContext } from "@/features/ai-generate/components/DocumentToQuestionsWizard";
import { toDeckSlidesBulk } from "@/features/ai-generate/mappers";
import { TARGET_NOUN, type GeneratedFor } from "@/features/ai-generate/types";
import { authoringApiFor, discardSeedOnlyDeck } from "@/features/deck/api/authoringApi";
import { productCopy } from "@/features/deck/productCopy";
import type { DeckProduct } from "@/features/deck/types";

// Dashboard "New Quiz" / "New Quest" tile. Its dialog starts a blank deck or
// one generated by AI from a document in My Files, then opens the editor.

const TILE: Record<DeckProduct, { circle: string; ring: string; cta: string; blurb: string; promptCard: boolean }> = {
	quiz: {
		circle: "bg-[#ed3a76]",
		ring: "focus-visible:ring-[#ed3a76]",
		cta: "text-[#ed3a76]",
		blurb: "Craft engaging quizzes to boost active participation, enhance knowledge retention, and elevate your educational impact.",
		promptCard: true,
	},
	quest: {
		circle: "bg-secondary",
		ring: "focus-visible:ring-secondary",
		cta: "text-[#f79a46]",
		blurb: "Run live polls, word clouds and open questions to hear every voice in the room, with results that appear as people answer.",
		promptCard: false,
	},
};

// Cards are real buttons (keyboard + focus ring). flex-col keeps each card's
// content at the top: a button centres its content vertically, which would
// push a card down next to a taller neighbour.
const cardClass =
	"group flex w-full flex-col rounded-[10px] pt-4 text-left focus:outline-none focus-visible:ring-2 focus-visible:ring-primary-600 focus-visible:ring-offset-2 disabled:cursor-wait";

export function NewDeckCard({ product }: { product: DeckProduct }) {
	const copy = productCopy(product);
	const tile = TILE[product];
	const noun = TARGET_NOUN[product];
	const api = authoringApiFor(product);
	const router = useRouter();
	const [dialogOpen, setDialogOpen] = useState(false);
	const [aiOpen, setAiOpen] = useState(false);
	// Busy until the new deck's editor opens; the ref stops a double create before the first await.
	const [creating, setCreating] = useState(false);
	const creatingRef = useRef(false);
	// A deck created for an AI run whose slides failed to save is reused on retry,
	// and deleted when the wizard closes without slides (no orphan "Untitled" deck).
	const aiDeckIdRef = useRef<number | null>(null);

	const createBlank = async () => {
		if (creatingRef.current) return;
		creatingRef.current = true;
		setCreating(true);
		try {
			const deck = await api.createDeck();
			router.push(copy.editHref(deck.id));
		} catch (error) {
			toast.error((error as Error)?.message || `The ${copy.noun} could not be created. Please try again.`);
			creatingRef.current = false;
			setCreating(false);
		}
	};

	/** Create the deck (title = topic), add the slides in one bulk call, open the editor. Throws to keep the wizard open. */
	const createFromDocument = async (result: GeneratedFor<DeckProduct>, { options }: GeneratedContext) => {
		const body = toDeckSlidesBulk(result);
		if (body.slides.length === 0) {
			throw new Error(`The AI didn't write any usable ${noun.plural}. Try other pages or a clearer topic.`);
		}
		let deckId = aiDeckIdRef.current;
		if (deckId === null) {
			const deck = await api.createDeck({ title: options.topic.trim().slice(0, 255) || null });
			deckId = deck.id;
			aiDeckIdRef.current = deckId;
		}
		const { slides } = await api.addSlidesBulk(deckId, body);
		aiDeckIdRef.current = null;
		toast.success(`${copy.Noun} created with ${slides.length} ${slides.length === 1 ? noun.singular : noun.plural}.`);
		router.push(copy.editHref(deckId));
	};

	const openAi = () => {
		setDialogOpen(false);
		setAiOpen(true);
	};

	const closeAi = () => {
		setAiOpen(false);
		const orphan = aiDeckIdRef.current;
		aiDeckIdRef.current = null;
		if (orphan !== null) void discardSeedOnlyDeck(api, orphan);
	};

	return (
		<div>
			<div
				role="button"
				tabIndex={0}
				aria-haspopup="dialog"
				aria-label={`New ${copy.Noun}`}
				onClick={() => setDialogOpen(true)}
				onKeyDown={(event) => {
					if (event.key === "Enter" || event.key === " ") {
						event.preventDefault();
						setDialogOpen(true);
					}
				}}
				className={cn(
					"mb-[30px] flex-[0_1_calc(33.333%_-_30px)] cursor-pointer overflow-hidden rounded-[28px] focus:outline-none focus-visible:ring-2 focus-visible:ring-offset-2",
					tile.ring
				)}
			>
				<div className="group relative block overflow-hidden bg-[#f3f3fe] px-5 py-[30px] transition-all duration-300 ease-in-out hover:no-underline">
					<div
						className={cn(
							"absolute right-[-75px] top-[-75px] z-0 h-[128px] w-[128px] rounded-full transition-transform duration-500 ease-in-out group-hover:scale-[10]",
							tile.circle
						)}
					/>
					<div className="relative z-10 text-[0.875rem] font-bold text-[#222] transition-colors duration-500 ease-in-out group-hover:text-white">
						New {copy.Noun}
					</div>
					<div className="relative z-20 flex items-center justify-center">
						<Image src={`/images/icons/${product}.svg`} alt="" width={150} height={60} className="transition-all duration-500 ease-in-out" />
					</div>
					<div className="relative z-10 flex items-center justify-center text-[14px]">
						<span className={cn("pl-1 font-bold transition-colors duration-500 ease-in-out group-hover:text-white", tile.cta)}>Click Here</span>
					</div>
				</div>
			</div>

			<Modal title={`Create a new ${copy.noun}`} open={dialogOpen} onClose={() => setDialogOpen(false)}>
				<div className="px-4 py-4 sm:px-6 lg:px-8">
					<h3 className="pb-2 text-[1rem] font-semibold capitalize">{copy.plural}</h3>
					<p className="w-full pb-5 text-[.875rem]">{tile.blurb}</p>

					<div className={cn("grid grid-cols-1 gap-4 sm:grid-cols-2", tile.promptCard && "lg:grid-cols-3")}>
						<button type="button" onClick={createBlank} disabled={creating} aria-busy={creating || undefined} className={cardClass}>
							<div className="flex w-full cursor-pointer items-center justify-center rounded-[10px] border border-[#2222] p-12 transition-all duration-500 ease-in-out group-hover:!border-[#222] sm:p-16">
								{creating ? (
									<>
										<Loader2 className="text-[#222] motion-safe:animate-spin" size={40} aria-hidden />
										<span role="status" className="sr-only">
											Creating your {copy.noun}…
										</span>
									</>
								) : (
									<FaPlus className="transition-all duration-500 ease-in-out group-hover:!text-[#222]" size={40} color="#2222" aria-hidden />
								)}
							</div>
							<h3 className="pt-2 text-[.875rem] font-semibold text-[#222] dark:text-white">Blank {copy.noun}</h3>
							<p className="text-[.875rem] text-[#7b7b7b]">Create your own {copy.noun} from scratch.</p>
						</button>

						<button type="button" onClick={openAi} className={cardClass}>
							<div className="relative flex w-full cursor-pointer items-center justify-center overflow-hidden rounded-[10px] border border-[#2222] bg-[#fda148] p-12 transition-all duration-500 ease-in-out group-hover:!border-[#222] sm:p-16">
								<div className="absolute right-0 top-0 hidden w-[120px] rounded-bl-[100px] rounded-br-[10px] rounded-tl-[100px] rounded-tr-[10px] bg-[#fdb774] py-[85px] sm:w-[150px] lg:block" />
								<ImFilesEmpty className="relative text-[#a35f1d] transition-all duration-500 ease-in-out group-hover:!text-[#222]" size={40} aria-hidden />
							</div>
							<h3 className="pt-2 text-[.875rem] font-semibold text-[#222] dark:text-white">AI Generate (From a File)</h3>
							<p className="text-[.875rem] text-[#7b7b7b]">Use a PDF, Word, PowerPoint or text file from My Files, or upload a new one.</p>
						</button>

						{tile.promptCard ? (
							// Not built yet: shown so people know it is coming; a button so keyboard users reach it.
							<button type="button" aria-disabled="true" className={cardClass}>
								<div className="relative flex w-full cursor-pointer items-center justify-center rounded-[10px] border border-[#2222] bg-[#BC5EB3] p-12 transition-all duration-500 ease-in-out group-hover:!border-[#222] sm:p-16">
									<div className="absolute right-0 top-0 hidden w-[120px] rounded-bl-[100px] rounded-br-[10px] rounded-tl-[100px] rounded-tr-[10px] bg-[#f590eb] py-[85px] sm:w-[150px] lg:block" />
									<ImFilesEmpty className="relative text-[#743e6e] transition-all duration-500 ease-in-out group-hover:!text-[#222]" size={40} aria-hidden />
								</div>
								<h3 className="pt-2 text-[.875rem] font-semibold">AI Generate (From URL / Prompts)</h3>
								<p className="text-[.875rem] text-[#7b7b7b]">Let AI build {copy.plural} from your chosen topics.</p>
							</button>
						) : null}
					</div>
				</div>
			</Modal>

			<DocumentToQuestionsModal
				open={aiOpen}
				onClose={closeAi}
				title={`Generate a ${copy.noun} from a document`}
				target={product}
				generateLabel={`Generate ${copy.noun}`}
				onGenerated={createFromDocument}
			/>
		</div>
	);
}
